// Real API checks: local production build only; never mutate real accounts.
import assert from "node:assert/strict";
const origin=process.argv[2]||"http://127.0.0.1:8787";
if(!["localhost","127.0.0.1"].includes(new URL(origin).hostname))throw new Error("Local QA only");
const uid=`qa_prefetch_${crypto.randomUUID()}`;
async function request(path,body,user=uid,status=200){
  const r=await fetch(`${origin}/api/${path}`,{method:body===undefined?"GET":"POST",headers:{"oai-authenticated-user-id":user,"oai-authenticated-user-email":`${user}@sites.test`,origin,"content-type":"application/json"},body:body===undefined?undefined:JSON.stringify(body)});
  const data=await r.json();assert.equal(r.status,status,JSON.stringify(data));return data;
}
const base=(await request("overview")).settings;
const settings={...base,currentBook:"CET4luan_1",newLimit:2,reviewLimit:1};
await request("settings",settings);
const words=[];
for(const word of ["custom-one","custom-two"])words.push((await request("words",{word,definition:"自定义词"})).word);
const now=Date.now();
const rows=[1,2].map(rank=>({word_id:`CET4luan_1:${rank}`,book_id:"CET4luan_1",word:`due-${rank}`,data:{due:new Date(now-3600_000+rank).toISOString(),last_review:new Date(now-86400_000).toISOString(),state:2,stability:3,difficulty:5,elapsed_days:1,scheduled_days:1,learning_steps:0,reps:2,lapses:0}}));
await request("import",{kind:"cards",rows});
const before=await request("backup");
const first=await request("study");
assert.equal(first.word.id,rows[0].word_id);
assert.equal(first.next.isNew,true,"Review lookahead must consume the current review quota");
assert.equal(first.next.word.bookId,"custom");
assert.notEqual(first.next.word.id,first.word.id);
assert.equal(first.next.next,undefined,"Bound prefetch to one card");
await request("study");
const after=await request("backup");
delete before.exportedAt;delete after.exportedAt;
assert.deepEqual(after,before,"Prefetch cannot change cards, history, or quotas");
const rate=(card,rating=4,id=crypto.randomUUID())=>request("review",{wordId:card.word.id,version:card.version,rating,requestId:id,duration:1000,includeNext:true});
let next=(await rate(first,1)).next;
assert.equal(next.word.id,first.next.word.id,"All ratings confirm the next candidate without an additional GET");
assert.equal(next.next.word.bookId,"custom");
assert.notEqual(next.next.word.id,next.word.id);
const key=crypto.randomUUID(),second=await rate(next,4,key);
const duplicate=await rate(next,4,key);
assert.equal(duplicate.next.word.id,second.next.word.id);
assert.equal((await request("overview")).stats.totalToday,2,"Retry must remain idempotent with bundled next-card response");
assert.equal(second.next.next.word,null,"Preview respects the final shared new-word slot");
const last=await rate(second.next);
assert.equal(last.next.word,null);
assert.equal((await request("overview")).stats.newToday,2);
await request("settings",{...settings,newLimit:3,reviewLimit:0});
const dueAgain=await request("study");
assert.equal(dueAgain.word.id,rows[1].word_id);
assert.equal(dueAgain.next.word.bookId,"CET4luan_1");
assert.equal(dueAgain.next.isNew,true);
const preset=(await rate(dueAgain)).next;
assert.equal(preset.word.id,dueAgain.next.word.id,"Review-to-book transition keeps the original ordering");
// A deleted prefetched word must not be resurrected by the review response.
const owner=`qa_prefetch_other_${crypto.randomUUID()}`;
await request("settings",{...base,currentBook:"custom",newLimit:10},owner);
for(const word of ["alpha","beta","gamma"])await request("words",{word,definition:"测试"},owner);
const stale=await request("study",undefined,owner);
await request("words/delete",{id:stale.next.word.id},owner);
const confirmed=await request("review",{wordId:stale.word.id,version:stale.version,rating:4,requestId:crypto.randomUUID(),includeNext:true},owner);
assert.notEqual(confirmed.next.word.id,stale.next.word.id);
assert.notEqual(confirmed.next.word.id,stale.word.id);
const stranger=await request("study",undefined,`qa_prefetch_empty_${crypto.randomUUID()}`);
assert.equal(stranger.word,null);assert.equal(stranger.next,undefined);
console.log("PASS: read-only one-card prefetch; review/custom/book order and quotas; canonical next; idempotency; deletion and user isolation.");
